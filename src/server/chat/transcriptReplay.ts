// Replay of an SDK transcript (JSONL under CLAUDE_CONFIG_DIR/projects) into
// read-only ChatEvents for chat history. Best-effort parser per design D5:
// unknown lines are ignored, a missing or unparseable file degrades to a
// "history unavailable" notice, and tool_use blocks with no tool_result —
// the only marker of a request that died with the process — are replayed as
// request pairs that history immediately marks cancelled (design D7).
import { parseEnvelope } from '../team/envelope'
import fs from 'node:fs'
import fsp from 'node:fs/promises'
import path from 'node:path'
import type { ChatEvent, ChatTurnTriggerTask } from '../../shared/chat'
import { validTime } from '../../shared/chatTime'
import { getClaudeConfigDir } from '../logDiscovery'
import {
  ASK_USER_QUESTION_TOOL,
  parseQuestions,
  toolResultText,
} from './contentBlocks'

export type TranscriptReplayStatus = 'ok' | 'missing' | 'unparseable'

/** Recorded `<command-name>` markup (both CLI generations, any tag order). */
const COMMAND_NAME_TAG = /<command-name>\s*([^<]*?)\s*<\/command-name>/
const COMMAND_ARGS_TAG = /<command-args>([\s\S]*?)<\/command-args>/
const LOCAL_COMMAND_STDOUT_TAG = /<local-command-stdout>([\s\S]*?)<\/local-command-stdout>/

/**
 * A user record Claude Code writes for a typed slash command, mapped back to
 * what the user typed: `/name` plus trimmed `<command-args>` when present.
 * Null when the text carries no `<command-name>` markup (unknown shapes fall
 * back to current rendering).
 */
function parseCommandMarkup(text: string): string | null {
  const name = COMMAND_NAME_TAG.exec(text)?.[1]?.replace(/^\/+/, '')
  if (!name) return null
  const args = COMMAND_ARGS_TAG.exec(text)?.[1]?.trim() ?? ''
  return `/${name}${args ? ` ${args}` : ''}`
}

/**
 * Inner text of a recorded `<local-command-stdout>` block; null when the
 * record carries no stdout markup or it is empty (nothing to replay).
 */
function parseLocalCommandStdout(text: string): string | null {
  const inner = LOCAL_COMMAND_STDOUT_TAG.exec(text)?.[1]
  return inner && inner.trim() ? inner : null
}

/** One recorded `<task-notification>` block (background tasks D5 replay). */
const TASK_NOTIFICATION_BLOCK = /<task-notification>([\s\S]*?)<\/task-notification>/g
const TASK_TAG = (name: string) => new RegExp(`<${name}>\\s*([\\s\\S]*?)\\s*</${name}>`)

/**
 * The tasks a task-notification user record carries: every
 * `<task-notification>` block parsed into the trigger shape. Empty when the
 * text holds no complete block (an `origin` marker alone still names a
 * self-started turn; the trigger then degrades to `resumed`).
 */
function parseTaskNotifications(text: string): ChatTurnTriggerTask[] {
  const tasks: ChatTurnTriggerTask[] = []
  for (const match of text.matchAll(TASK_NOTIFICATION_BLOCK)) {
    const inner = match[1] ?? ''
    const taskId = TASK_TAG('task-id').exec(inner)?.[1]
    if (!taskId) continue
    const toolCallId = TASK_TAG('tool-use-id').exec(inner)?.[1]
    const status = TASK_TAG('status').exec(inner)?.[1]
    const summary = TASK_TAG('summary').exec(inner)?.[1]
    tasks.push({
      taskId,
      ...(toolCallId ? { toolCallId } : {}),
      status: status ?? 'unknown',
      ...(summary ? { summary } : {}),
    })
  }
  return tasks
}

/**
 * Whether a user record is the CLI's task-notification turn opener: the SDK
 * stamps `origin.kind: "task-notification"`, and the content is wholly the
 * markup. Either mark qualifies; the record never replays as a user message.
 */
function isTaskNotificationRecord(record: Record<string, unknown>, text: string): boolean {
  const origin = record.origin
  if (typeof origin === 'object' && origin !== null) {
    const kind = (origin as Record<string, unknown>).kind
    if (kind === 'task-notification') return true
  }
  const trimmed = text.trim()
  return trimmed.startsWith('<task-notification>') && trimmed.endsWith('</task-notification>')
}

export interface TranscriptReplay {
  status: TranscriptReplayStatus
  /**
   * Replayed history events, or a single "history unavailable" notice when
   * the transcript is missing/unparseable. Events carry `sequence: 0` (order
   * is the array order) and stable ids derived from the transcript, so
   * re-parses of the same file produce the same ids.
   */
  events: ChatEvent[]
  /**
   * The working directory the conversation ended in (worktree tracking
   * design D3), or null when the transcript holds none. Null whenever the
   * history itself is unavailable.
   */
  cwd: string | null
}

/**
 * A session title the agent persisted as a transcript state row:
 * `ai-title` (generated by Claude Code, source `auto`) or `custom-title`
 * (set by a rename inside Claude Code, source `manual` — design D7).
 */
export interface TranscriptTitle {
  title: string
  source: 'auto' | 'manual'
}

export interface ParsedTranscript {
  events: ChatEvent[]
  /** tool_use ids with no matching tool_result in this transcript. */
  unmatchedToolCallIds: string[]
  /** Lines that were not valid JSON (truncated tail, corruption). */
  invalidLines: number
  /**
   * The transcript's current title, or null when there is none. Title rows
   * are state re-emitted at turn boundaries, so among generated titles the
   * last one is current (D2). A `custom-title` is user-set and terminal
   * (D1/D7), so it is never displaced by a later `ai-title`.
   */
  title: TranscriptTitle | null
  /**
   * The newest non-empty working directory the transcript records (design
   * D3) — where the conversation actually is, which may be a worktree the
   * agent entered. Null when no line records one.
   */
  cwd: string | null
}

/**
 * Locate `<sdkSessionId>.jsonl` under the Claude config's projects dir.
 * Searched by filename rather than an encoded project path: the encoding of
 * the session's cwd is not ours to reconstruct (worktree dirs encode with a
 * doubled separator), while the file name is exactly the SDK session id.
 */
export function findTranscriptPath(sdkSessionId: string): string | null {
  const name = `${sdkSessionId}.jsonl`
  const root = path.join(getClaudeConfigDir(), 'projects')
  return findNewestFile(root, name, 3)
}

function findNewestFile(
  root: string,
  fileName: string,
  maxDepth: number
): string | null {
  // Mutable holder: the walk is recursive and TS cannot see those writes.
  const best = { path: null as string | null, mtime: -1 }
  const walk = (dir: string, depth: number): void => {
    let entries: fs.Dirent[]
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (depth < maxDepth) walk(full, depth + 1)
      } else if (entry.isFile() && entry.name === fileName) {
        const mtime = fs.statSync(full).mtimeMs
        if (mtime > best.mtime) {
          best.path = full
          best.mtime = mtime
        }
      }
    }
  }
  walk(root, 0)
  return best.path
}

/**
 * Parse one complete transcript line as a title state row (`ai-title` or
 * `custom-title`). Null for anything else: a non-title row, an invalid JSON
 * line (a truncated tail), or a title row whose title field is missing or
 * blank. Cheap to call per line — non-title rows reject on a substring test
 * before any JSON parsing.
 */
export function parseTranscriptTitleLine(
  line: string
): TranscriptTitle | null {
  if (!line.includes('"ai-title"') && !line.includes('"custom-title"')) {
    return null
  }
  let record: Record<string, unknown>
  try {
    const parsed: unknown = JSON.parse(line)
    if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
      return null
    }
    record = parsed as Record<string, unknown>
  } catch {
    return null
  }
  const isAiTitle = record.type === 'ai-title'
  if (!isAiTitle && record.type !== 'custom-title') return null
  const value = record[isAiTitle ? 'aiTitle' : 'customTitle']
  if (typeof value !== 'string' || !value.trim()) return null
  return { title: value.trim(), source: isAiTitle ? 'auto' : 'manual' }
}

/**
 * Parse transcript JSONL content into read-only events. Tolerant: lines that
 * are not valid JSON and lines of an unknown kind are skipped. `unmatchedToolCallIds`
 * lists tool uses that never got a result — see `withCancelledRequests`.
 * `includeSidechain` keeps sidechain records (a subagent transcript file is
 * all sidechain) for the worker-body reader (workers design D5).
 */
export function parseTranscriptContent(
  content: string,
  options?: { includeSidechain?: boolean }
): ParsedTranscript {
  const events: ChatEvent[] = []
  const resultToolCallIds = new Set<string>()
  const unmatchedCandidates: string[] = []
  let invalidLines = 0
  let turnCounter = 0
  let lineIndex = 0
  let title: TranscriptTitle | null = null
  let cwd: string | null = null

  for (const rawLine of content.split('\n')) {
    lineIndex += 1
    const line = rawLine.trim()
    if (!line) continue
    const lineTitle = parseTranscriptTitleLine(line)
    if (lineTitle) {
      // Generated titles: the latest is current (D2). A user-set title is
      // terminal (D1/D7), so it holds until another user-set one replaces it.
      if (lineTitle.source === 'manual' || title?.source !== 'manual') {
        title = lineTitle
      }
      continue
    }
    let record: Record<string, unknown>
    try {
      const parsed: unknown = JSON.parse(line)
      if (!parsed || typeof parsed !== 'object') {
        invalidLines += 1
        continue
      }
      record = parsed as Record<string, unknown>
    } catch {
      // Truncated last line or corruption: skip, the caller decides if the
      // file as a whole is unparseable.
      invalidLines += 1
      continue
    }
    if (
      record.isMeta === true ||
      (record.isSidechain === true && options?.includeSidechain !== true)
    ) {
      continue
    }
    // Worktree tracking design D3: the newest non-empty one wins. Parent
    // parses already dropped sidechain records above; a worker-body parse
    // keeps them, and its caller simply ignores the captured cwd.
    const lineCwd = recordCwd(record)
    if (lineCwd) cwd = lineCwd
    const type = record.type
    const lineUuid =
      typeof record.uuid === 'string' && record.uuid
        ? record.uuid
        : `line-${lineIndex}`
    // The replay join key (plan-workspace §4.3): the record's own uuid when
    // it carries one — never the `line-<n>` synthetic above.
    const recordUuid = typeof record.uuid === 'string' && record.uuid ? record.uuid : undefined
    // An undated record stays undated (chat-transcript-layout D2): an empty
    // `at` means unknown, never the replay time presented as recorded.
    const at =
      typeof record.timestamp === 'string' && validTime(record.timestamp)
        ? record.timestamp
        : ''
    const message = asRecord(record.message)
    const contentValue = message?.content

    if (type === 'system') {
      if (record.subtype === 'compact_boundary') {
        events.push({
          id: `hist-${lineUuid}`,
          sequence: 0,
          at,
          type: 'notice',
          text: 'Context compacted',
        })
      } else if (
        record.subtype === 'local_command' &&
        typeof record.content === 'string'
      ) {
        const output = parseLocalCommandStdout(record.content)
        if (output !== null) {
          events.push({
            id: `hist-${lineUuid}`,
            sequence: 0,
            at,
            type: 'command_output',
            turnId: `hist-turn-${turnCounter}`,
            text: output,
          })
        }
      }
      // Other system subtypes are informational; ignored.
      continue
    }
    if (type === 'assistant' && record.isApiErrorMessage === true) {
      // An API-error reply (chat-context-exhaustion D2: e.g. the CLI's
      // synthetic "Prompt is too long") replays as the error the live chat
      // showed, never as assistant text.
      events.push({
        id: `hist-${lineUuid}`,
        sequence: 0,
        at,
        type: 'error',
        message: apiErrorText(contentValue),
      })
      continue
    }
    if (type === 'user' || type === 'assistant') {
      if (typeof contentValue === 'string') {
        if (type === 'user') {
          if (isTaskNotificationRecord(record, contentValue)) {
            // The wake turn's opener (background tasks D5): a trigger line,
            // never a user message bubble.
            const tasks = parseTaskNotifications(contentValue)
            turnCounter += 1
            events.push({
              id: `hist-${lineUuid}`,
              sequence: 0,
              at,
              type: 'turn_started',
              turnId: `hist-turn-${turnCounter}`,
              trigger: tasks.length > 0 ? { kind: 'task', tasks } : { kind: 'resumed' },
            })
            continue
          }
          const typed = parseCommandMarkup(contentValue) ?? contentValue
          const peer = parseEnvelope(typed)
          if (typed.length > 0) {
            turnCounter += 1
            events.push({
              id: `hist-${lineUuid}`,
              sequence: 0,
              at,
              turnId: `hist-turn-${turnCounter}`,
              ...(recordUuid ? { messageUuid: recordUuid } : {}),
              ...(peer ? { type: 'peer_message' as const, ...peer } : { type: 'user_message' as const, text: typed }),
            })
          }
        } else {
          // Assistant lines carry blocks, not plain text; tolerate a string
          // form if the writer ever produces one.
          events.push({
            id: `hist-${lineUuid}`,
            sequence: 0,
            at,
            type: 'assistant_text',
            turnId: `hist-turn-${turnCounter}`,
            messageId: stringField(message, 'id') ?? lineUuid,
            text: contentValue,
          })
        }
        continue
      }
      const blocks = Array.isArray(contentValue) ? contentValue : []
      let blockIndex = 0
      for (const block of blocks) {
        blockIndex += 1
        const blockRecord = asRecord(block)
        if (!blockRecord) continue
        const blockId = `hist-${lineUuid}-${blockIndex}`
        const turnId = `hist-turn-${turnCounter}`
        const blockType = blockRecord.type
        if (blockType === 'text' && typeof blockRecord.text === 'string') {
          if (type === 'user') {
            if (isTaskNotificationRecord(record, blockRecord.text)) {
              const tasks = parseTaskNotifications(blockRecord.text)
              turnCounter += 1
              events.push({
                id: blockId,
                sequence: 0,
                at,
                type: 'turn_started',
                turnId: `hist-turn-${turnCounter}`,
                trigger: tasks.length > 0 ? { kind: 'task', tasks } : { kind: 'resumed' },
              })
            } else {
              const typed = parseCommandMarkup(blockRecord.text) ?? blockRecord.text
              const peer = parseEnvelope(typed)
              if (typed.length > 0) {
                turnCounter += 1
                events.push({
                  id: blockId,
                  sequence: 0,
                  at,
                  turnId: `hist-turn-${turnCounter}`,
                  ...(recordUuid ? { messageUuid: recordUuid } : {}),
                  ...(peer ? { type: 'peer_message' as const, ...peer } : { type: 'user_message' as const, text: typed }),
                })
              }
            }
          } else {
            events.push({
              id: blockId,
              sequence: 0,
              at,
              type: 'assistant_text',
              turnId,
              messageId: stringField(message, 'id') ?? lineUuid,
              text: blockRecord.text,
            })
          }
        } else if (blockType === 'tool_use') {
          const toolCallId =
            typeof blockRecord.id === 'string' ? blockRecord.id : ''
          if (!toolCallId) continue
          unmatchedCandidates.push(toolCallId)
          events.push({
            id: blockId,
            sequence: 0,
            at,
            type: 'tool_call',
            turnId,
            toolCallId,
            tool:
              typeof blockRecord.name === 'string' ? blockRecord.name : 'tool',
            input: blockRecord.input,
          })
        } else if (blockType === 'tool_result') {
          const toolCallId =
            typeof blockRecord.tool_use_id === 'string'
              ? blockRecord.tool_use_id
              : ''
          if (!toolCallId) continue
          resultToolCallIds.add(toolCallId)
          events.push({
            id: blockId,
            sequence: 0,
            at,
            type: 'tool_result',
            turnId,
            toolCallId,
            output: toolResultText(blockRecord.content),
            ...(blockRecord.is_error === true ? { isError: true } : {}),
          })
        }
        // thinking and other block kinds are not surfaced in history.
      }
      continue
    }
    // Unknown line types (mode, cost-state, file-history, ...) are ignored.
  }

  return {
    events,
    unmatchedToolCallIds: unmatchedCandidates.filter(
      (id) => !resultToolCallIds.has(id)
    ),
    invalidLines,
    title,
    cwd,
  }
}

/**
 * Splice a request pair after each still-unmatched tool_call: the request the
 * process died holding, immediately marked cancelled. A live driver's
 * in-flight tool ids can be excluded — those are covered by live events.
 */
export function withCancelledRequests(
  events: ChatEvent[],
  unmatchedToolCallIds: string[],
  options?: { excludeToolCallIds?: Set<string> }
): ChatEvent[] {
  const pending = new Set(
    unmatchedToolCallIds.filter(
      (id) => !options?.excludeToolCallIds?.has(id)
    )
  )
  if (pending.size === 0) return events
  const result: ChatEvent[] = []
  for (const event of events) {
    result.push(event)
    if (event.type !== 'tool_call' || !pending.has(event.toolCallId)) continue
    pending.delete(event.toolCallId)
    const requestEvent = cancelledRequestEvent(event)
    result.push(requestEvent, {
      id: `hist-cancel-${event.toolCallId}`,
      sequence: 0,
      at: event.at,
      type: 'request_resolved',
      requestId: event.toolCallId,
      outcome: 'cancelled',
    })
  }
  return result
}

function cancelledRequestEvent(
  event: Extract<ChatEvent, { type: 'tool_call' }>
): ChatEvent {
  const questions =
    event.tool === ASK_USER_QUESTION_TOOL && isRecord(event.input)
      ? parseQuestions(event.input)
      : null
  if (questions) {
    return {
      id: `hist-ask-${event.toolCallId}`,
      sequence: 0,
      at: event.at,
      type: 'question_request',
      turnId: event.turnId,
      requestId: event.toolCallId,
      questions,
    }
  }
  return {
    id: `hist-ask-${event.toolCallId}`,
    sequence: 0,
    at: event.at,
    type: 'approval_request',
    turnId: event.turnId,
    requestId: event.toolCallId,
    tool: event.tool,
    input: event.input,
  }
}

/**
 * Replay a transcript file into history events. `filePath: null` counts as
 * missing. A missing or unreadable/unparseable file yields the
 * "history unavailable" notice; the caller decides whether resume is still
 * allowed (design D5: an existing-but-unparseable transcript may resume —
 * the SDK reads the file itself — while a missing one may not).
 */
export function replayTranscriptFile(
  filePath: string | null,
  options?: { excludeToolCallIds?: Set<string> }
): TranscriptReplay {
  if (!filePath) return historyUnavailable('missing')
  let content: string
  try {
    content = fs.readFileSync(filePath, 'utf8')
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code
    return historyUnavailable(code === 'ENOENT' ? 'missing' : 'unparseable')
  }
  return replayContent(content, options)
}

/**
 * The latest title a transcript file holds, or null when the file is
 * unreadable or holds no title row. The catch-up read for sessions restored
 * after a restart (chat-session-naming design D4).
 */
export function readTranscriptTitle(filePath: string): TranscriptTitle | null {
  try {
    return parseTranscriptContent(fs.readFileSync(filePath, 'utf8')).title
  } catch {
    return null
  }
}

/**
 * The working directory a transcript file's conversation ended in, or null
 * when the file is unreadable or records none. The restart catch-up for
 * sessions restored after the agent moved (worktree tracking design D3).
 */
export function readTranscriptCwd(filePath: string): string | null {
  try {
    return parseTranscriptContent(fs.readFileSync(filePath, 'utf8')).cwd
  } catch {
    return null
  }
}

/** Boot catch-up fields extracted from one transcript parse pass. */
export interface TranscriptMeta {
  title: TranscriptTitle | null
  cwd: string | null
}

/**
 * Title and cwd from a SINGLE read + parse pass — the boot catch-up needs
 * both (naming design D4, worktree tracking design D3), and reading the file
 * twice would double the startup parse cost. Null fields when unreadable.
 */
export function readTranscriptMeta(filePath: string): TranscriptMeta {
  try {
    const parsed = parseTranscriptContent(fs.readFileSync(filePath, 'utf8'))
    return { title: parsed.title, cwd: parsed.cwd }
  } catch {
    return { title: null, cwd: null }
  }
}

/** Async mirror of {@link readTranscriptMeta} over fs/promises. */
export async function readTranscriptMetaAsync(
  filePath: string
): Promise<TranscriptMeta> {
  let content: string
  try {
    content = await fsp.readFile(filePath, 'utf8')
  } catch {
    return { title: null, cwd: null }
  }
  try {
    const parsed = parseTranscriptContent(content)
    return { title: parsed.title, cwd: parsed.cwd }
  } catch {
    return { title: null, cwd: null }
  }
}

/** Async mirror of {@link findTranscriptPath} over fs/promises. */
export async function findTranscriptPathAsync(
  sdkSessionId: string
): Promise<string | null> {
  const name = `${sdkSessionId}.jsonl`
  const root = path.join(getClaudeConfigDir(), 'projects')
  return findNewestFileAsync(root, name, 3)
}

async function findNewestFileAsync(
  root: string,
  fileName: string,
  maxDepth: number
): Promise<string | null> {
  // Mutable holder: the walk is recursive and TS cannot see those writes.
  const best = { path: null as string | null, mtime: -1 }
  const walk = async (dir: string, depth: number): Promise<void> => {
    let entries: fs.Dirent[]
    try {
      entries = await fsp.readdir(dir, { withFileTypes: true })
    } catch {
      return
    }
    for (const entry of entries) {
      const full = path.join(dir, entry.name)
      if (entry.isDirectory()) {
        if (depth < maxDepth) await walk(full, depth + 1)
      } else if (entry.isFile() && entry.name === fileName) {
        // Transcripts can disappear between readdir and stat. Keep looking
        // so one removed or unreadable file cannot abort every restored row.
        try {
          const mtime = (await fsp.stat(full)).mtimeMs
          if (mtime > best.mtime) {
            best.path = full
            best.mtime = mtime
          }
        } catch {
          continue
        }
      }
    }
  }
  await walk(root, 0)
  return best.path
}

/** Async mirror of {@link replayTranscriptFile} over fs/promises. */
export async function replayTranscriptFileAsync(
  filePath: string | null,
  options?: { excludeToolCallIds?: Set<string> }
): Promise<TranscriptReplay> {
  if (!filePath) return historyUnavailable('missing')
  let content: string
  try {
    content = await fsp.readFile(filePath, 'utf8')
  } catch (error) {
    const code = (error as NodeJS.ErrnoException).code
    return historyUnavailable(code === 'ENOENT' ? 'missing' : 'unparseable')
  }
  return replayContent(content, options)
}

/** The parse shared by the sync and async file replays. */
function replayContent(
  content: string,
  options?: { excludeToolCallIds?: Set<string> }
): TranscriptReplay {
  try {
    const parsed = parseTranscriptContent(content)
    // Content that produced no events at all but failed to parse is a parser
    // failure; an empty or bookkeeping-only file is simply an empty history.
    if (parsed.events.length === 0 && parsed.invalidLines > 0) {
      return historyUnavailable('unparseable')
    }
    return {
      status: 'ok',
      events: withCancelledRequests(
        parsed.events,
        parsed.unmatchedToolCallIds,
        options
      ),
      cwd: parsed.cwd,
    }
  } catch {
    return historyUnavailable('unparseable')
  }
}

/** The one "history unavailable" replay (D8: the Codex rollout replay shares it). */
export function historyUnavailable(
  status: 'missing' | 'unparseable'
): TranscriptReplay {
  return {
    status,
    cwd: null,
    events: [
      {
        id: 'hist-unavailable',
        sequence: 0,
        at: new Date().toISOString(),
        type: 'notice',
        text:
          status === 'missing'
            ? 'History unavailable — the conversation transcript was not found. Restore it or create a new chat session to start over.'
            : 'History unavailable — the conversation transcript could not be parsed.',
      },
    ],
  }
}

/** The text of an API-error reply: its string content or joined text blocks. */
function apiErrorText(content: unknown): string {
  if (typeof content === 'string' && content.trim()) return content.trim()
  const text = (Array.isArray(content) ? content : [])
    .map((block) => asRecord(block))
    .map((block) => (block?.type === 'text' && typeof block.text === 'string' ? block.text : ''))
    .join('\n')
    .trim()
  return text || 'The model request failed'
}

/**
 * The working directory one parsed transcript record carries at write time
 * (worktree tracking design D3; attachment rows spell it
 * snapshot.workingDirectory), or null. Shared by the full parse and the
 * streaming meta reader (`transcriptMeta.ts`) so both apply one rule.
 */
export function recordCwd(record: Record<string, unknown>): string | null {
  const snapshot = asRecord(asRecord(record.attachment)?.snapshot)
  return stringField(record, 'cwd') ?? stringField(snapshot, 'workingDirectory')
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return value && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return asRecord(value) !== null
}

function stringField(
  record: Record<string, unknown> | null,
  key: string
): string | null {
  const value = record?.[key]
  return typeof value === 'string' && value ? value : null
}
